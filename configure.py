# --- manifest ---------------------------------------------------------------
def load_manifest(path: Path) -> dict:
    with path.open("rb") as f:
        data = tomllib.load(f)
    # Named flag profiles ([flags] table): EVERY [[unit]] selects one with
    # `flags = "<name>"`. The profiles ARE the full flag sets - there is no
    # separate global default to inherit and no per-TU append, so each TU's flag
    # choice is one explicit, greppable name. /GX and /GR are profile choices
    # (cpp, cpp-o1, cpp-rtti), never bolt-ons: a stray `extra` key is a hard error.
    profiles = data.get("flags", {})
    if not profiles:
        raise SystemExit(f"{path}: [flags] must define at least one profile")
    units = data.get("unit", [])
    if not units:
        raise SystemExit(f"{path}: no [[unit]] entries")
    seen = set()
    for u in units:
        for key in ("unit", "source", "flags"):
            if key not in u:
                raise SystemExit(f"{path}: a [[unit]] is missing '{key}'")
        if u["unit"] in seen:
            raise SystemExit(f"{path}: duplicate unit '{u['unit']}'")
        seen.add(u["unit"])
        if u["flags"] not in profiles:
            raise SystemExit(f"{path}: unit '{u['unit']}' references unknown "
                             f"flags profile '{u['flags']}' "
                             f"(defined: {sorted(profiles)})")
        if "extra" in u:
            raise SystemExit(
                f"{path}: unit '{u['unit']}' sets 'extra' - per-TU flag bolt-ons "
                f"are not supported. Add (or reuse) a [flags] profile carrying the "
                f"FULL set instead; /GR lives in the `cpp-rtti` profile.")
        # Copy the profile - never mutate the shared list.
        u["cflags"] = list(profiles[u["flags"]])
    return data


# --- build.ninja ------------------------------------------------------------
def emit_link_phase(w: ninja_syntax.Writer, base_objs: list) -> None:
    """Graph phase 2: link the base objs -> candidate (non-runnable) .EXE + .map.

    Runs the genuine VC5 link.exe (5.10.7303) under wine via
    scripts/gruntz/build/link.py over a @response file (VC5 link has a short argv
    limit under wine), against the retail library set - static CRT + MFC via the
    objs' own -defaultlib: directives, DX6, version/winmm, and the mss32/smackw32
    import libs synthesised by gruntz.build.import_lib. The reconstruction is still
    PARTIAL, so /FORCE stays on; the deliverable is the `.map`, which gives each
    function's link-assigned RVA + source object. That, cross-referenced with the
    retail RVAs, is what recovers the build order for matching (intra-TU order =
    source-definition order; cross-TU order = object link order). See
    docs/link-order-investigation.md and `gruntz link`.

    This is an OPT-IN target (`ninja candidate`), kept OUT of the default `all` so
    a normal `gruntz build` is unaffected. link.py manages its own wineserver.

    The `.rsrc` section comes from `gruntz.build.rescomp`, the project's resource
    compiler (the toolchain tarball ships `cvtres.exe` but no `rc.exe`): it parses
    src/Gruntz/Gruntz.rc - real, tracked rc grammar covering all 57 authorable
    resources - and writes the Win32 `.RES` container itself. Only the 18
    ICON/CURSOR art resources are carried bytes (config/retail/rsrc/data/); the
    `rescomp check` build gate byte-proves both halves against retail's own image.
    """
    w.comment("=== PHASE 2: link -> candidate .EXE + .map (opt-in: `ninja candidate`) ===")
    cand = "build/exe/GRUNTZ.candidate.EXE"
    res = "build/gen/gruntz.res"
    w.rule("rescomp", command=f"{PY} {RESCOMP} build --out $out",
           description=".rc + art blobs -> .RES")
    w.build(res, "rescomp",
            inputs=["config/retail/rsrc/manifest.tsv", "src/Gruntz/Gruntz.rc"],
            implicit=[RESCOMP])
    w.rule("link",
           command=f"{PY} {LINK} --out {cand} --objs-dir {BASE_DIR} --res {res}",
           description="link base objs -> candidate EXE + map")
    w.build([cand, "build/exe/GRUNTZ.candidate.map"], "link",
            inputs=base_objs, implicit=[LINK, res,
                                        "scripts/gruntz/build/msdis_stub.py",
                                        "scripts/gruntz/build/import_lib.py"])
    # The README's link-status block is refreshed HERE and nowhere else in the
    # build: `gruntz build` does not link, so the block is only as fresh as the
    # last `ninja candidate`. It states the candidate's digest and link time so a
    # stale block is visible rather than silent.
    #
    # It carries a per-section BYTE-similarity column from gruntz.audit.image_diff,
    # which reads build/gen/delink_data_manifest.tsv - and prune_orphan_artifacts()
    # deletes that file whenever it prunes, so the delink stamp is an input here or
    # `ninja candidate` would score the image against a manifest that is not there.
    w.rule("linkscore",
           command=f"{PY} -m gruntz.audit.link_sections --write-readme && "
                   f"touch $out",
           description="candidate EXE -> README link status")
    w.build("build/gen/.link_score.stamp", "linkscore", inputs=[cand],
            implicit=["scripts/gruntz/audit/link_sections.py",
                      "scripts/gruntz/audit/image_diff.py",
                      "build/objdiff/.delink.stamp"])
    w.build("candidate", "phony",
            inputs=[cand, "build/gen/.link_score.stamp"])
    w.newline()


def emit_ninja(manifest: dict, out: Path) -> None:
    build = manifest["build"]
    units = manifest["unit"]
    # build.ninja's global $cflags default = the first [flags] profile; a unit's
    # edge overrides it only when its resolved flags differ. Generation detail -
    # every unit names its profile explicitly in the manifest.
    global_cflags = next(iter(manifest["flags"].values()))

    with out.open("w", encoding="utf-8") as f:
        w = ninja_syntax.Writer(f)
        w.comment("GENERATED by configure.py from config/units.toml - do not edit.")
        w.comment("Regenerate: python3 configure.py")
        w.newline()

        w.variable("ninja_required_version", "1.7")
        w.variable("py", PY)
        w.variable("cflags", " ".join(global_cflags))
        w.newline()

        # PHASE 1: compile each TU's source -> base .obj via the wine-cl wrapper.
        # Emitted BEFORE the generator edge only so the include scan has run and
        # `scanned_files` is complete; ninja does not care about edge order.
        cl_edges = []
        for u in units:
            obj = f"{BASE_DIR}/{u['unit']}.obj"
            variables = {"unit": u["unit"]}
            # The unit's resolved [flags] profile; emit a per-edge override only
            # when it differs from build.ninja's global $cflags default.
            if u["cflags"] != global_cflags:
                variables["cflags"] = " ".join(u["cflags"])
            cl_edges.append((obj, u["source"], [CC_WRAP] + local_headers(u["source"]),
                             variables))

        # Regenerate build.ninja when the manifest, configure.py, or ANY file the
        # include scan read changes.
        #
        # The dep lists on the `cl` edges below are baked HERE, at configure time,
        # from the #include graph as it stood. So an edit that changes that graph -
        # adding an #include, adding/renaming/deleting a header - invalidates them,
        # and without the scanned set on this edge nothing notices: ninja keeps
        # using the stale list and a later edit to a newly-included header does not
        # rebuild its TU. That is silent, and it is exactly the failure mode a
        # byte-neutrality claim from a header-only edit depends on not happening.
        # /showIncludes would let cl emit real depfiles, but MSVC 5.0 rejects it
        # (D4002), so the scan is what we have - make it self-invalidating.
        w.rule("configure",
               command=f"{PY} configure.py",
               description="configure.py (regenerate build.ninja)",
               generator=True)
        w.build("build.ninja", "configure",
                implicit=["configure.py", "config/units.toml",
                          "scripts/gruntz/build/ninja_syntax.py",
                          *sorted(scanned_files)])
        w.newline()

        w.comment("=== PHASE 1: compile -> base .obj (cl /O2 /MT under wine) ===")
        w.rule("cl",
               command=f"{PY} {CC_WRAP} --out $out --src $in -- $cflags",
               description="cl $unit")
        w.newline()

        base_objs = []
        for obj, src, implicit, variables in cl_edges:
            base_objs.append(obj)
            w.build(obj, "cl", inputs=src, implicit=implicit, variables=variables)
        w.newline()

        # LABELS: per-TU fragment, then a cheap merge -> symbol_names.csv.
        # Each fragment is one TU's clang-IR pass (the expensive step), so a single
        # edit re-emits only THAT unit's IR instead of all ~23. Both edges carry
        # `restat` so an unchanged symbol set (a pure code edit) stops here and does
        # NOT cascade into delink/objdiff. The IR emit needs the clangd compdb's
        # per-TU include flags (labels.py falls back to bare MS flags if absent).
        # Each TU also emits functions.json/globals.json fragments (per-RVA
        # signatures + declared global types for apply.py's Ghidra enrichment);
        # merge_labels combines all three so apply.py sees EVERY unit, not just the
        # last TU built.
        w.comment("=== LABELS: per-TU fragments -> merge -> symbol_names.csv ===")
        w.rule("gen_labels_one",
               command=f"{PY} {GEN_LABELS} --tu $src --obj $obj --unit $unit "
                       f"--compdb {COMPDB} --out $csvfrag "
                       f"--functions-out $funcfrag --globals-out $globfrag",
               description="gen_labels $unit",
               restat=True)
        compdb_dep = [COMPDB] if (REPO / COMPDB).exists() else []
        zlib_dep = [p for p in ("config/retail/functions_zlib.tsv",
                                "config/retail/data_zlib.tsv")
                    if (REPO / p).exists()]
        # DATA extents come directly from pylibclang's Type.get_size() in this
        # per-TU edge.  structs.json is a separate whole-tree audit cache and must
        # never make label correctness depend on when that cache was refreshed.
        frags, func_frags, glob_frags = [], [], []
        for u in units:
            frag = f"{LABELS_DIR}/{u['unit']}.csv"
            funcfrag = f"{LABELS_DIR}/{u['unit']}.functions.json"
            globfrag = f"{LABELS_DIR}/{u['unit']}.globals.json"
            obj = f"{BASE_DIR}/{u['unit']}.obj"
            frags.append(frag)
            func_frags.append(funcfrag)
            glob_frags.append(globfrag)
            w.build([frag, funcfrag, globfrag], "gen_labels_one",
                    inputs=u["source"],
                    implicit=[obj, GEN_LABELS, "config/units.toml"]
                             + compdb_dep + zlib_dep,
                    variables={"src": u["source"], "obj": obj, "unit": u["unit"],
                               "csvfrag": frag,
                               "funcfrag": funcfrag, "globfrag": globfrag})
        w.rule("merge_labels",
               command=f"{PY} {GEN_LABELS} --merge $csvfrags --out {GEN_NAMES} "
                       f"--merge-functions $funcfrags --functions-out {FUNCTIONS_JSON} "
                       f"--merge-globals $globfrags --globals-out {GLOBALS_JSON}",
               description="merge_labels -> symbol_names.csv + functions/globals.json",
               restat=True)
        # Vtable catalogs are consumed only by the cheap merge. Catalog edits
        # must not rerun clang IR over every translation unit.
        vtbl_dep = ["config/retail/vtables_game.csv", "config/retail/vtables_library.csv"]
        # Reviewed per-TU static-copy pins are folded in at merge time too.
        copies_dep = [str(p.relative_to(REPO))
                      for p in [REPO / "config/static_data_copies.tsv"] if p.exists()]
        w.build([GEN_NAMES, FUNCTIONS_JSON, GLOBALS_JSON], "merge_labels",
                inputs=frags + func_frags + glob_frags,
                implicit=[GEN_LABELS] + vtbl_dep + copies_dep,
                variables={"csvfrags": " ".join(frags),
                           "funcfrags": " ".join(func_frags),
                           "globfrags": " ".join(glob_frags)})
        w.newline()

        # TARGET (delink) half: one rule produces all in-scope <unit>.c.obj.
        w.comment("=== TARGET: delink GRUNTZ.EXE -> named per-unit .c.obj ===")
        unit_args = " ".join(f"--unit {u['unit']}" for u in units)
        # The declared output is a single STAMP, NOT the ~500 per-unit .c.obj. Some
        # units have no named symbol yet (they pair with dummy.obj below), so
        # declaring every <unit>.c.obj as an output made ninja treat delink as
        # perpetually unbuilt - re-running the full ~24s delink on EVERY build,
        # including no-ops. Keyed on GEN_NAMES (symbol_names.csv, written
        # content-idempotently by labels.py), delink now fires ONLY when a symbol
        # changes (name / RVA / size / kind) - never on a pure code-body edit.
        # `gruntz build --force-delink` removes the stamp to force a re-delink.
        delink_stamp = f"{OBJDIFF_DIR}/.delink.stamp"
        w.rule("delink",
               command=(f"{PY} {DELINK} --exe {EXE} --functions {FUNCTIONS} "
                        f"--names-map {GEN_NAMES} "
                        f"--reloc-alias-manifest {RELOC_ALIASES} "
                        f"--pdb-dir {PDB_DIR} --delink-dir {DELINK_RAW} "
                        f"--target-dir {TARGET_DIR} --stamp {delink_stamp} {unit_args}"),
               description="delink GRUNTZ.EXE -> target objs")
        target_objs = [f"{TARGET_DIR}/{u['unit']}.c.obj" for u in units]
        w.build(delink_stamp, "delink",
                inputs=[EXE, FUNCTIONS, GEN_NAMES],
                # data_manifest.py (+ the data_audit PE classifier it imports):
                # delink.py regenerates the data/section manifests in-process on every
                # run, so editing either must re-delink too - otherwise objdiff keeps
                # scoring the previous manifest.
                implicit=[DELINK, "scripts/gruntz/build/synth_pdb.py",
                          "scripts/gruntz/build/data_manifest.py",
                          "scripts/gruntz/core/data_audit.py",
                          RELOC_ALIASES,
                          # synth_pdb carries the tracked FID library labels into
                          # the fake PDB, so the delinked target speaks the same
                          # CRT/MFC symbol names our base objs reference. Editing
                          # a row must re-delink or objdiff keeps the old name.
                          "config/retail/functions_static_libs.tsv",
                          # vtable_rows() reads the RTTI slot map through
                          # vtable_hierarchy -> vtable_scan; both decide vtable extents.
                          "scripts/gruntz/core/vtable_hierarchy.py",
                          "scripts/gruntz/core/vtable_scan.py"])
        w.newline()

        # NORMALIZE: rewrite compiler-private data names + jump-table labels of
        # every base/target obj into content-addressed comparison copies under
        # build/objdiff/normalized/ (objdiff pairs BY NAME; the real objs are
        # untouched, so this is matching-neutral and can only sharpen the diff).
        # One stamped edge drives the whole set (mirrors delink); the driver
        # mtime-skips unchanged objs, so a single base recompile only re-normalizes
        # that one obj. Keyed on the base objs + the delink stamp so it re-runs when
        # either side changes. See docs/build-system.md (data-symbol normalization).
        w.comment("=== NORMALIZE: base/target -> content-addressed comparison copies ===")
        normalize_stamp = f"{OBJDIFF_DIR}/.normalize.stamp"
        unit_norm_args = " ".join(f"--unit {u['unit']}" for u in units)
        w.rule("normalize",
               command=(f"{PY} {NORMALIZE} --base-dir {BASE_DIR} "
                        f"--target-dir {TARGET_DIR} --out-dir {NORM_DIR} "
                        f"--stamp {normalize_stamp} {unit_norm_args}"),
               description="normalize base/target objs")
        w.build(normalize_stamp, "normalize",
                inputs=base_objs + [delink_stamp],
                implicit=[NORMALIZE, NORMALIZE_MOD])
        w.newline()

        # OBJDIFF MANIFEST: objdiff.json pairs each base obj with its target obj.
        # Whether a unit pairs with its real <unit>.c.obj or the empty dummy.obj is
        # read off the DELINK OUTPUT, so this edge runs after the delink stamp (and
        # therefore after gen_labels, which delink itself depends on). That is what
        # makes a unit added this build pair correctly in ONE build - and what stops
        # a unit whose only contribution is data from being left on the dummy, which
        # objdiff scores 100.00% with zero totals.
        objdiff_json = f"{OBJDIFF_DIR}/objdiff.json"
        w.comment("=== OBJDIFF: symbol_names.csv -> objdiff.json (post-labels) ===")
        w.rule("gen_objdiff",
               command=f"{PY} configure.py --emit-objdiff",
               description="gen_objdiff (symbol_names.csv -> objdiff.json)",
               restat=True)
        w.build(objdiff_json, "gen_objdiff",
                # AFTER the delink: the pairing is read off the target objs the
                # delinker actually wrote, not predicted from symbol_names.csv.
                inputs=[GEN_NAMES, delink_stamp],
                implicit=["configure.py", "config/units.toml"])
        w.newline()

        # REPORT: the objdiff summary, in-graph so it regenerates ONLY when an obj
        # (or the pairing) changes - not via an unconditional call every build. A
        # pure code edit changes the edited unit's base obj -> report.json updates;
        # a no-op build leaves it untouched, so `gruntz build` can skip its feedback
        # tail (nothing rebuilt -> nothing to report).
        report_json = f"{OBJDIFF_DIR}/report.json"
        w.comment("=== REPORT: objs + pairing -> report.json (objdiff-cli) ===")
        w.rule("report",
               command=f"objdiff-cli report generate -p {OBJDIFF_DIR} -o {report_json}",
               description="objdiff report -> report.json")
        # Reads the NORMALIZED comparison copies (objdiff.json points at them); the
        # normalize stamp transitively carries the base-obj + delink dependencies.
        w.build(report_json, "report",
                inputs=[normalize_stamp, objdiff_json])
        w.newline()

        # Convenience aliases.
        w.comment("=== aliases ===")
        w.build("base", "phony", inputs=base_objs)
        w.build("target", "phony", inputs=[delink_stamp])
        w.build("all", "phony",
                inputs=base_objs + [delink_stamp, objdiff_json, report_json])
        w.default(["all"])
        w.newline()

        emit_link_phase(w, base_objs)


