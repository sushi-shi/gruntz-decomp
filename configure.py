#!/usr/bin/env python3
"""configure.py - generate the Gruntz matching build from the units manifest.

Single source of truth: config/units.toml (per-TU). This script reads it and
emits, from one manifest:

  * build.ninja            - the native incremental build graph (Linux ninja
                             driving `wine cl` via scripts/gruntz/core/cc_wrap.py).
  * build/objdiff/objdiff.json - the objdiff project pairing each recompiled
                             base obj against its delinked target obj BY SYMBOL
                             NAME.

(The clang compile DB lives in build/clangd/, generated by scripts/gruntz/init/clangd.py
- the build itself needs no compdb; ninja tracks deps.)

Two graph phases (see docs/build-system.md):
  1. compile -> .obj   - IMPLEMENTED. Each manifest unit's source compiles to
                         build/objdiff/base/<unit>.obj via the `cl` rule.
  2. link -> .EXE      - IMPLEMENTED but OPT-IN. emit_link_phase() emits a `link`
                         rule + `candidate` phony, kept OUT of the default `all`
                         (build only via `ninja candidate` / `gruntz link`). It
                         links the base objs into a non-runnable candidate EXE +
                         .map for the link-order study (intra-TU order = source
                         order, cross-TU = object order); a normal build never
                         links. See docs/link-order-investigation.md.

The TARGET (delink) half is orchestrated as a ninja `delink` rule that runs
scripts/gruntz/build/delink.py (synth_pdb -> vostok-delinker -> collect <unit>.c.obj).

Run inside `nix develop`:
    python3 configure.py        # regenerate build.ninja + objdiff.json
    ninja                       # build the base objs + delink the target
    objdiff-cli report generate -p build/objdiff -o build/objdiff/report.json

Add a TU: add an [[unit]] block to config/units.toml and annotate each function
in its src/ file with a `// @address:` comment (build/gen/symbol_names.csv is
regenerated from those), then re-run configure.py and ninja.
"""

