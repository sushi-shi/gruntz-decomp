bool CButeMgr::TagList() {
    ConsumeChar();
    if (!ScanTok()) {
        return false;
    }
    if (m_token == BUTETOK_END) {
        return true;
    }
    if (m_token != BUTETOK_TAG_OPEN) {
        return false;
    }
    while (m_token != BUTETOK_END) {
        if (!Tag()) {
            return false;
        }
        if (m_writeMode) {

            TableOfItems* grp = static_cast<TableOfItems*>(ModifiedTags()->lookup(m_sTagName));
            if (grp) {
                grp->traverse(&AuxTabItemsSave, m_pSaveData);
            }
        }
        if (!ScanTok()) {
            return false;
        }
        if (m_token == BUTETOK_END) {
            return true;
        }
        if (m_token != BUTETOK_TAG_OPEN) {
            if (m_token != BUTETOK_NAME) {
                return false;
            }
            if (!StatementList()) {
                return false;
            }
        }
    }
    return true;
}

bool CButeMgr::Save() {
    Reset();
    if (m_sAttributeFilename.IsEmpty()) {
        return false;
    }

    m_writeMode = true;
    m_bPutChar = true;

    char block[4096];

    ifstream input(m_sAttributeFilename, ios::nocreate | ios::binary);
    input.seekg(0, ios::end);
    i32 length = input.tellg();
    input.clear();
    input.seekg(0);

    strstream source(new char[length], length, ios::in | ios::out);
    if (m_bCrypt) {
        m_cryptMgr.Decrypt(input, source);
        m_pSaveData = new iostream(new strstreambuf(length));
        m_pSaveData->precision(100);
    } else {
        while (!input.eof()) {
            input.read(block, sizeof(block));
            source.write(block, input.gcount());
        }
        input.close();
        m_pSaveData = new fstream(m_sAttributeFilename, ios::in | ios::out | ios::binary);
        m_pSaveData->precision(100);
    }

    source.clear();
    m_pData = &source;
    TagList();
    m_newTagTab.traverse(&NewTabsSave, m_pSaveData);
    m_pSaveData->clear();

    if (m_bCrypt) {
#ifdef __clang__

        ofstream output(m_sAttributeFilename, ios::binary);
        m_cryptMgr.Encrypt(*m_pSaveData, output);
#else
        m_cryptMgr.Encrypt(*m_pSaveData, ofstream(m_sAttributeFilename, ios::binary));
#endif
    }

    delete[] source.str();
    if (m_bCrypt) {
        delete m_pSaveData->rdbuf();
    }
    delete m_pSaveData;

    m_bPutChar = false;
    m_writeMode = false;
    return true;
}

